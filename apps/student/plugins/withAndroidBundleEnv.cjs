const {createRunOncePlugin, withAppBuildGradle} = require('expo/config-plugins');

// QAPreview and endpoint flips must invalidate the Hermes bundle. Gradle does
// not track process environment, so without this the JS-bundle task stays
// up-to-date and ships the previous mode's bundle (the stale-bundle bug).
//
// Implementation notes (19 Nov):
// - v1 used tasks.whenTaskAdded + providers.environmentVariable(...).get():
//   deterministic hang at DefaultBuildControllers.awaitCompletion on Expo/RN
//   composite builds (three runs) — must never return.
// - v2 used tasks.matching().configureEach + provider passthrough: the task
//   stayed UP-TO-DATE across a flag flip, so its inputs never took effect.
// - v3 resolves plain String values at task realization (findProperty with
//   System.getenv fallback). scripts/build_android_apk.sh passes the same
//   values as -P flags so both paths agree.
const MARKER = '// hostelxpress: bundle env inputs (generated by withAndroidBundleEnv)';

const ENV_KEYS = [
  'EXPO_PUBLIC_QA_PREVIEW',
  'EXPO_PUBLIC_API_URL',
  'EXPO_PUBLIC_SUPABASE_URL',
  'EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY',
];

function bundleEnvInputs() {
  const lines = [
    MARKER,
    'tasks.matching({ task -> task.name.startsWith(\'createBundle\') }).configureEach { task ->',
    ...ENV_KEYS.map(key => `    task.inputs.property('${key}', project.findProperty('${key}') ?: System.getenv('${key}') ?: 'unset')`),
    '}',
  ];
  return '\n' + lines.join('\n') + '\n';
}

function withAndroidBundleEnv(config) {
  return withAppBuildGradle(config, mod => {
    mod.modResults.contents = mod.modResults.contents.replace(
      /\n\/\/ hostelxpress: bundle env inputs \(generated by withAndroidBundleEnv\)[\s\S]*$/,
      '',
    );
    mod.modResults.contents += bundleEnvInputs();
    return mod;
  });
}

module.exports = createRunOncePlugin(withAndroidBundleEnv, 'with-android-bundle-env', '1.2.0');
